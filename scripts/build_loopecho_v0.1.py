q = P('C11', '2'); W(q, (q[0] + g(3), q[1]))
Rv('R10', '100k', q[0] + g(3), q[1] + g(3.5), side='r', d='Output pull-down'); W((q[0] + g(3), q[1]), P('R10', '1')); GND(P('R10', '2'))
W((q[0] + g(3), q[1]), (q[0] + g(6), q[1])); lab('OUT', (q[0] + g(6), q[1]))

