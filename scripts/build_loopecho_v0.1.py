for ref, x in (('U2', 27), ('U3', 33), ('U4', 39)):
    s.part(ref, 'Amplifier_Operational', 'TL072', 'TL072', g(x), g(56), 0, unit=3, text='ic'); V9(P(ref, '8')); GND(P(ref, '4'))
s.part('J1', 'Connector_Generic', 'Conn_01x02', '9V / GND', g(8), g(63), 180, text=((g(6), g(60)), (g(6), g(61.5)), 'right'))
