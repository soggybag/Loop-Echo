"""Loop Echo (working name): single PT2399 delay with an effects loop in the FEEDBACK path, plus delay-time modulation.
PT2399 network from the user's Small Time (Eagle, 2022). True bypass (no tails JFET).
  - U2A input buffer (DRY); U2B inverting mixer (dry + MIX), as Small Time
  - PT2399 (U1) on its own 5 V regulator (U5 78L05); TIME = 1k + B50k from VCO (pin 6) to ground
  - wet (W) -> U3A SEND buffer -> TRS insert TIP; RING -> U3B RETURN buffer -> 1k + 1N4148 limiter -> REPEAT -> PT2399 input.
    No plug: the jack's ring-normal contact ties RETURN to SEND, so it's a normal delay.
    Only the repeats go round the loop: the first echo is clean, each later echo is processed again.
  - LFO U4 (integrator + Schmitt, RATE 47k + B1M, 1u: ~0.5-12 Hz) -> AC-coupled DEPTH -> 100k -> VCO pin: wow / chorus on the repeats
Breadboard-first: no footprints yet.
usage: build_loopecho.py <out.kicad_sch>"""
from sch import *
import sys
OUT = sys.argv[1]
g = lambda n: round(n * 2.54, 3)
s = Sheet('LoopEcho', 'A1')
W = lambda *p: s.wire(*p)
P = s.P
def GND(p): s.power('GND', p)
def V9(p): s.power('+9V', p)
def V5(p): s.power('+5V', p)
def lab(n, p, side='r'): s.label(n, p, side)
def Rh(ref, v, cx, y, d=''): s.part(ref, 'Device', 'R', v, cx, y, 90, desc=d, text='t')
def Rv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'R', v, x, cy, 0, desc=d, text=side)
def Ch(ref, v, cx, y, d=''): s.part(ref, 'Device', 'C', v, cx, y, 90, desc=d, text='t')
def Cv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'C', v, x, cy, 0, desc=d, text=side)
def CPh(ref, v, cx, y, d=''): s.part(ref, 'Device', 'C_Polarized', v, cx, y, 90, desc=d, text='t')
def CPv(ref, v, x, cy, side='r', d=''): s.part(ref, 'Device', 'C_Polarized', v, x, cy, 0, desc=d, text=side)
def gnd_down(p, n=1): W(p, (p[0], p[1] + g(n))); GND((p[0], p[1] + g(n)))
def lab_at(p, name, dx=2, side='r'):
    q = (p[0] + g(dx) * (1 if side == 'r' else -1), p[1]); W(p, q); lab(name, q, side)
PINS = {1: ('3', '2', '1'), 2: ('5', '6', '7')}
def OP(ref, unit, x, ytop):
    s.part(ref, 'Amplifier_Operational', 'TL072', 'TL072', x, ytop + 2.54, 0, unit=unit, text='ic')
    pl, mi, ou = PINS[unit]
    return P(ref, pl), P(ref, mi), P(ref, ou)
def follower(ref, unit, x, ytop):
    pl, mi, ou = OP(ref, unit, x, ytop)
    W(mi, (mi[0] - g(1), mi[1]), (mi[0] - g(1), mi[1] + g(3)), (ou[0] + g(1), mi[1] + g(3)), (ou[0] + g(1), ou[1]))
    W(ou, (ou[0] + g(1), ou[1]))
    return pl, (ou[0] + g(1), ou[1])
def pot(ref, v, name, x, y, mirror='x', text=None):
    s.part(ref, 'Device', 'R_Potentiometer', v, x, y, 0, mirror=mirror, desc=name, extra={'Panel': name},
           text=text or ((x - g(4), y + g(2)), (x - g(4), y + g(3.5)), 'right'))

